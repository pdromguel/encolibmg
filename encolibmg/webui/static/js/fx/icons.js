/** <svg> pixel icon; size follows the font (1em) unless CSS says otherwise. */
export function icon(name, cls = "") {
  const g = ICONS[name];
  if (!g) return "";
  const rects = [];
  g.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === "#") rects.push(svg`<rect x=${x} y=${y} width="1" height="1"/>`);
    else if (c === "+") rects.push(svg`<rect x=${x} y=${y} width="1" height="1" opacity=".45"/>`);
  }));
  return html`<svg class="pi ${cls}" viewBox="0 0 9 9" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
}
